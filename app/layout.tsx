import type { Metadata } from "next";
import { headers } from "next/headers";
import "./globals.css";
import AemFetchSourceBanner from "./components/AemFetchSourceBanner";
import type { AemTarget } from "./lib/aem-client";
import { INSURANCE_JOURNEY_MODEL_DEFINITION } from "./lib/universalEditorModels";
// import { isUniversalEditorRequest } from "./lib/universalEditor";

const aueConnection =
  process.env.NEXT_PUBLIC_AEM_CONNECTION ?? process.env.NEXT_PUBLIC_AEM_HOST;

const aem = process.env.AEM_PUBLISH_HOST!;

export const metadata: Metadata = {
  title: "Create Next App",
  description: "Generated by create next app",
};

const universalEditorModelDefinitionJson = JSON.stringify(
  INSURANCE_JOURNEY_MODEL_DEFINITION,
);

function resolveAemTargetFromRequest(
  requestHeaders: Headers,
): AemTarget {
  const explicit = requestHeaders.get("x-aem-target");
  if (
    explicit === "author" ||
    explicit === "preview" ||
    explicit === "publish"
  ) {
    return explicit;
  }

  if (requestHeaders.get("x-ue-request") === "1") {
    return "author";
  }

  return "publish";
}

export default async function RootLayout({
  children,
}: Readonly<{
  children: React.ReactNode;
}>) {
  const requestHeaders = await headers();
  const aemTarget = resolveAemTargetFromRequest(requestHeaders);

  return (
    <html
      lang="en"
      // className={
      //   isUniversalEditor
      //     ? "caravan-ue-document antialiased"
      //     : "h-full antialiased"
      // }
      className="h-full antialiased"
      suppressHydrationWarning
    >
      <head>
        <script
          src="https://universal-editor-service.adobe.io/cors.js"
          async
        ></script>
        {aueConnection ? (
          <meta
            name="urn:adobe:aue:system:aemconnection"
            content={`aem:${aueConnection}`}
            data-rh="true"
          />
        ) : null}
        {/* <meta
          name="urn:adobe:aue:config:service"
          content="https://localhost:8000"
        /> */}
        <meta name="urn:adobe:aue:config:disable" content="duplicate" />
        <script
          type="application/vnd.adobe.aue.model+json"
          dangerouslySetInnerHTML={{
            __html: universalEditorModelDefinitionJson,
          }}
        />
        <meta name="test" content={`aem:${aem}`} />
      </head>
      <body
        // className={
        //   isUniversalEditor ? "caravan-ue-body flex flex-col" : "flex flex-col"
        // }
        className="flex flex-col"
        suppressHydrationWarning
      >
        <AemFetchSourceBanner aemTarget={aemTarget} />
        {children}
      </body>
    </html>
  );
}
